"""Stable OpenAPI contract validation issue."""

from __future__ import annotations

from typing import Literal

from domain.value_model import ValueModel

type OpenAPIValidationIssueCode = Literal[
    "OPENAPI_VERSION_UNSUPPORTED",
    "OPENAPI_SERVICE_METADATA_MISSING",
    "OPENAPI_SERVICE_METADATA_INVALID",
    "OPENAPI_INFO_VERSION_MISSING",
    "OPENAPI_RPC_PATH_INVALID",
    "OPENAPI_HTTP_METHOD_UNSUPPORTED",
    "OPENAPI_OPERATION_ID_MISSING",
    "OPENAPI_OPERATION_ID_INVALID",
    "OPENAPI_OPERATION_ID_DUPLICATE",
    "OPENAPI_OPERATION_ID_OWNED_BY_OTHER_SERVICE",
    "OPENAPI_OAUTH2_SECURITY_SCHEME_MISSING",
    "OPENAPI_OAUTH2_SECURITY_SCHEME_INVALID",
    "OPENAPI_OAUTH2_SCOPE_MISSING",
    "OPENAPI_OAUTH2_SCOPE_INVALID",
    "OPENAPI_OAUTH2_SCOPE_OPERATION_MISMATCH",
    "OPENAPI_SECURITY_MISMATCH",
    "OPENAPI_EXTERNAL_REF_FORBIDDEN",
    "OPENAPI_REF_UNSUPPORTED",
    "OPENAPI_WEBHOOKS_UNSUPPORTED",
    "OPENAPI_CALLBACKS_UNSUPPORTED",
    "OPENAPI_DOCUMENT_INVALID",
    "OPENAPI_DOCUMENT_TOO_LARGE",
    "OPENAPI_TOO_MANY_OPERATIONS",
    "OPENAPI_NESTING_TOO_DEEP",
]


class OpenAPIValidationIssue(ValueModel):
    """One safe finite validation problem without document fragments."""

    code: OpenAPIValidationIssueCode
    location: str
    message: str
